import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

import { format } from "oxfmt";

// oxlint-disable-next-line no-underscore-dangle
const __dirname = path.dirname(fileURLToPath(new URL(import.meta.url)));

const constantsFilePath = path.join(__dirname, "../src/constants.ts");

const testSuitesDir = path.join(__dirname, "../tests");

const targets = fs
  .readdirSync(testSuitesDir, { withFileTypes: true })
  .filter((dirent) => dirent.isDirectory())
  .map((dirent) => dirent.name);

const constantsFileContent = `// This file is auto-generated by gen-constants.ts. Do not edit manually.

export const targets = ${JSON.stringify(targets)} as const;
`;

const formatted = await format(constantsFilePath, constantsFileContent);
fs.writeFileSync(constantsFilePath, formatted.code);
