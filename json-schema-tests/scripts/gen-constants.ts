import * as fs from "node:fs";
import * as path from "node:path";

import { format } from "oxfmt";

const targetsFilePath = path.join(import.meta.dirname, "../constants/targets.gen.ts");
const testSuitesDir = path.join(import.meta.dirname, "../tests");

const targets = fs
  .readdirSync(testSuitesDir, { withFileTypes: true })
  .filter((dirent) => dirent.isDirectory())
  .map((dirent) => dirent.name);

const targetsFileContent = `// This file is auto-generated by gen-constants.ts. Do not edit manually.

export default ${JSON.stringify(targets)} as const;
`;

const formattedTargets = await format(targetsFilePath, targetsFileContent);
fs.writeFileSync(targetsFilePath, formattedTargets.code);

const remotesFilePath = path.join(import.meta.dirname, "../constants/remotes.gen.ts");
const remotesDir = path.join(import.meta.dirname, "../remotes");

const remoteFiles = fs
  .readdirSync(remotesDir, { recursive: true, withFileTypes: true })
  .filter((file) => file.isFile() && file.name.endsWith(".json"))
  .map((file) => {
    const filePath = path.join(file.parentPath, file.name);
    return path.relative(remotesDir, filePath).split(path.sep).join("/");
  });

const entries = remoteFiles
  .map((rel) => {
    const filePath = path.join(remotesDir, rel);
    const content = fs.readFileSync(filePath, "utf-8");
    return `  "http://localhost:1234/${rel}": ${content.trim()}`;
  })
  .join(",\n");

const remotesFileContent = `// This file is auto-generated by gen-constants.ts. Do not edit manually.

export default {
${entries},
} satisfies Record<string, {} | boolean>;
`;

const formattedRemotes = await format(remotesFilePath, remotesFileContent);
fs.writeFileSync(remotesFilePath, formattedRemotes.code);
