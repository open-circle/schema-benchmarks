import * as fs from "node:fs/promises";
import * as path from "node:path";

// the built libraries, so this needs `pnpm run --filter schemas build` first
import { libraries } from "@schema-benchmarks/schemas/libraries";
import ts from "dedent";
import { format } from "oxfmt";

/**
 * Reads the installed version of every benchmarked library from the built benchmark configs, so
 * E2E tests can assert against real versions instead of hand-maintained strings that go stale.
 *
 * Run it with `pnpm run e2e:gen-versions` (or `pnpm pree2e`), after building `schemas`.
 */
const versions: Record<string, string> = {};

for (const getConfig of Object.values(libraries)) {
  const { library } = await getConfig();
  versions[library.name] = library.version;
}

const outputPath = path.join(import.meta.dirname, "../utils/library-versions.gen.ts");

const content = ts`// This file is auto-generated by gen-library-versions.ts. Do not edit manually.

/** Installed library versions, read from the built benchmark configs. */
export const libraryVersions = ${JSON.stringify(versions, null, 2)} as const satisfies Record<
  string,
  string
>;
`;

const formatted = await format(outputPath, content);
await fs.writeFile(outputPath, formatted.code);
