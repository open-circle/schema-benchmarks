import * as fs from "node:fs/promises";
import * as path from "node:path";

// the built libraries, so this needs `pnpm run build` first - same as the benchmarks
import { jsonSchemaDirectionSchema, jsonSchemaTargetSchema } from "@schema-benchmarks/schemas";
import { libraries } from "@schema-benchmarks/schemas/libraries";

/**
 * Regenerates the accepted JSON schemas from what the libraries currently generate, so a library
 * changing its output is a reviewable diff rather than a hand written one.
 *
 * Run it with `pnpm run gen:json-schemas`, and read the diff before committing - the point of the
 * list is that a new shape gets looked at.
 */
const generated: Record<string, Array<{ libraryNames: Array<string>; jsonSchema: object }>> = {};

for (const getConfig of Object.values(libraries)) {
  const config = await getConfig();
  if (!config.jsonSchema) continue;
  for (const benchConfig of [config.jsonSchema].flat()) {
    for (const target of jsonSchemaTargetSchema.options) {
      for (const direction of jsonSchemaDirectionSchema.options) {
        let jsonSchema;
        try {
          jsonSchema = benchConfig.generate({ target, direction });
        } catch {
          // libraries throw for anything they can't convert
          continue;
        }
        const key = `${target}/${direction}`;
        const entries = (generated[key] ??= []);
        const existing = entries.find(
          (entry) => JSON.stringify(entry.jsonSchema) === JSON.stringify(jsonSchema),
        );
        if (existing) existing.libraryNames.push(config.library.name);
        else entries.push({ libraryNames: [config.library.name], jsonSchema });
      }
    }
  }
}

const lines = [
  'import type { JsonSchemaDirection, JsonSchemaTarget } from "@schema-benchmarks/schemas";',
  "",
  "/**",
  " * Every JSON schema the libraries are allowed to generate for the benchmark subject, listed with",
  " * the libraries that generate it.",
  " *",
  " * Libraries disagree on how to describe the same type - where `$schema` goes, whether",
  " * `additionalProperties` is set, whether named types are hoisted into `$defs` - so the schemas",
  " * aren't normalised and compared. A library generating a shape that isn't listed here fails the",
  " * test, so the difference gets looked at and accepted deliberately.",
  " *",
  " * Generated by `pnpm run gen:json-schemas`.",
  " */",
  "export const acceptedJsonSchemas = {",
];
for (const target of jsonSchemaTargetSchema.options) {
  lines.push(`  "${target}": {`);
  for (const direction of jsonSchemaDirectionSchema.options) {
    lines.push(`    ${direction}: [`);
    for (const { libraryNames, jsonSchema } of generated[`${target}/${direction}`] ?? []) {
      lines.push(`      // ${libraryNames.join(", ")}`);
      lines.push(`      ${JSON.stringify(jsonSchema)},`);
    }
    lines.push("    ],");
  }
  lines.push("  },");
}
lines.push("} satisfies Record<JsonSchemaTarget, Record<JsonSchemaDirection, Array<object>>>;");

await fs.writeFile(
  path.resolve(import.meta.dirname, "../test/accepted-json-schemas.ts"),
  `${lines.join("\n")}\n`,
);
console.log("Generated accepted JSON schemas - run `pnpm format` to tidy them up");
